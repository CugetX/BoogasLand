// Exact spreadsheet Dust drop distribution per Geode hit:
// 60% -> 1, 20% -> 2, 10% -> 3, 6% -> 4, 4% -> 5
export function rollGeodeDust(randFn = Math.random) {
  const r = randFn();
  if (r < 0.60) return 1;
  if (r < 0.80) return 2;
  if (r < 0.90) return 3;
  if (r < 0.96) return 4;
  return 5;
}

